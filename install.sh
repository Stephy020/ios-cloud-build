#!/usr/bin/env bash
# Installs the `skydrop` command for Linux bash or Windows Git Bash.
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) BIN_DIR="$HOME/bin" ;;
  *) BIN_DIR="$HOME/.local/bin" ;;
esac

# A small wrapper script instead of a symlink: Git Bash copies symlinks.
mkdir -p "$BIN_DIR"
{
  echo '#!/usr/bin/env bash'
  echo '# Generated by skydrop/install.sh'
  printf 'export SKYDROP_HOME=%q\n' "$HERE"
  echo 'exec bash "$SKYDROP_HOME/bin/skydrop" "$@"'
} > "$BIN_DIR/skydrop"
chmod +x "$BIN_DIR/skydrop" "$HERE/bin/skydrop"
echo "✓ Installed $BIN_DIR/skydrop"

# Skydrop used to be called ios-cloud; remove that old command if this installer made it.
if [ -f "$BIN_DIR/ios-cloud" ] && grep -q 'Generated by ios-cloud-build/install.sh' "$BIN_DIR/ios-cloud"; then
  rm -f "$BIN_DIR/ios-cloud"
  echo "✓ Removed the old 'ios-cloud' command (it's now called skydrop)"
fi

case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *)
    MARK="# added by skydrop"
    if ! grep -qF "$MARK" "$HOME/.bashrc" 2>/dev/null; then
      printf '\n%s\nexport PATH="%s:$PATH"\n' "$MARK" "$BIN_DIR" >> "$HOME/.bashrc"
      echo "✓ Added $BIN_DIR to your PATH in ~/.bashrc"
    fi
    echo "  Open a new terminal (or run: export PATH=\"$BIN_DIR:\$PATH\") before using skydrop."
    export PATH="$BIN_DIR:$PATH"
    ;;
esac

echo
"$BIN_DIR/skydrop" doctor || true
