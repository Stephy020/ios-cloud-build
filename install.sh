#!/usr/bin/env bash
# Installs the `ios-cloud` command for Linux bash or Windows Git Bash.
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) BIN_DIR="$HOME/bin" ;;
  *) BIN_DIR="$HOME/.local/bin" ;;
esac

# A small wrapper script instead of a symlink: Git Bash copies symlinks.
mkdir -p "$BIN_DIR"
{
  echo '#!/usr/bin/env bash'
  echo '# Generated by ios-cloud-build/install.sh'
  printf 'export IOS_CLOUD_HOME=%q\n' "$HERE"
  echo 'exec bash "$IOS_CLOUD_HOME/bin/ios-cloud" "$@"'
} > "$BIN_DIR/ios-cloud"
chmod +x "$BIN_DIR/ios-cloud" "$HERE/bin/ios-cloud"
echo "✓ Installed $BIN_DIR/ios-cloud"

case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *)
    MARK="# added by ios-cloud-build"
    if ! grep -qF "$MARK" "$HOME/.bashrc" 2>/dev/null; then
      printf '\n%s\nexport PATH="%s:$PATH"\n' "$MARK" "$BIN_DIR" >> "$HOME/.bashrc"
      echo "✓ Added $BIN_DIR to your PATH in ~/.bashrc"
    fi
    echo "  Open a new terminal (or run: export PATH=\"$BIN_DIR:\$PATH\") before using ios-cloud."
    export PATH="$BIN_DIR:$PATH"
    ;;
esac

echo
"$BIN_DIR/ios-cloud" doctor || true
